# --------------------------------------------------------------------------- генерация
def stable_choice(key: str, options: list[str]) -> str:
    digest = hashlib.sha256(key.encode("utf-8")).digest()
    return options[digest[0] % len(options)]


def lower_first(text: str) -> str:
    return text[0].lower() + text[1:] if text else text


def variants(question: str, extra_casual: bool) -> list[str]:
    """Базовая формулировка + вежливый/срочный префикс (+ небрежная без пунктуации)."""
    out = [question]
    out.append(stable_choice(question, PREFIXES) + lower_first(question))
    if extra_casual:
        casual = question.rstrip("?!. ").lower()
        if casual != question:
            out.append(casual)
    return out


def answer_json(answer: str | None, confidence: float) -> str:
    return json.dumps({"answer": answer, "confidence": confidence}, ensure_ascii=False)


def build_rows() -> list[dict]:
    rows: list[dict] = []
    seen: set[str] = set()

    def add(
        question: str, answer: str | None, conf: float, kind: str, topic: str
    ) -> None:
        if question in seen:
            return
        seen.add(question)
        rows.append(
            {
                "instruction": question,
                "input": "",
                "output": answer_json(answer, conf),
                "kind": kind,
                "topic": topic,
            }
        )

    for i, (topic, conf, answer, questions) in enumerate(FACTS):
        for j, q in enumerate(questions):
            for variant in variants(q, extra_casual=(i + j) % 2 == 0):
                add(variant, answer, conf, "on_topic", topic)
    for topic, conf, answer, questions in PARTIAL:
        for q in questions:
            for variant in variants(q, extra_casual=True):
                add(variant, answer, conf, "partial", topic)
    for q in VAGUE_QUESTIONS:
        for variant in variants(q, extra_casual=True):
            add(variant, VAGUE_ANSWER, 0.3, "vague", "vague")
    for topic, questions in OFF_TOPIC.items():
        for j, q in enumerate(questions):
            for variant in variants(q, extra_casual=j % 2 == 0):
                add(variant, None, 0.0, "off_topic", topic)
    return rows


def to_messages(row: dict) -> dict:
    return {
        "messages": [
            {"role": "user", "content": row["instruction"]},
            {"role": "assistant", "content": row["output"]},
        ]
    }


def save_jsonl(rows: list[dict], path: Path) -> None:
    path.write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    assert len(rows) >= MIN_TOTAL, f"мало примеров: {len(rows)} < {MIN_TOTAL}"
    for row in rows:  # каждый ответ обязан парситься и соответствовать схеме
        parsed = json.loads(row["output"])
        assert set(parsed) == {"answer", "confidence"}, row
        assert parsed["answer"] is None or isinstance(parsed["answer"], str), row
        assert 0.0 <= parsed["confidence"] <= 1.0, row

    # Отложенный экзамен не должен пересекаться с обучением
    test = (
        [{"question": q, "kind": "on_topic", "topic": t} for t, q in TEST_ON_TOPIC]
        + [{"question": q, "kind": "partial", "topic": t} for t, q in TEST_PARTIAL]
        + [{"question": q, "kind": "vague", "topic": t} for t, q in TEST_VAGUE]
        + [{"question": q, "kind": "off_topic", "topic": t} for t, q in TEST_OFF_TOPIC]
    )
    train_questions = {r["instruction"] for r in rows}
    overlap = [t["question"] for t in test if t["question"] in train_questions]
    assert not overlap, f"вопросы экзамена попали в обучение: {overlap}"

    rng = random.Random(SEED)
    rng.shuffle(rows)
    # val — стратифицированно по видам, чтобы в нём были и отказы
    by_kind: dict[str, list[dict]] = {}
    for r in rows:
        by_kind.setdefault(r["kind"], []).append(r)
    val: list[dict] = []
    for kind, bucket in by_kind.items():
        take = max(1, round(VAL_SIZE * len(bucket) / len(rows)))
        val.extend(bucket[:take])
    val_ids = {id(r) for r in val}
    train = [r for r in rows if id(r) not in val_ids]

    save_jsonl(rows, OUT_DIR / "train.jsonl")
    save_jsonl([to_messages(r) for r in train], OUT_DIR / "train_messages.jsonl")
    save_jsonl([to_messages(r) for r in val], OUT_DIR / "val_messages.jsonl")
    save_jsonl(test, OUT_DIR / "test_questions.jsonl")

    kinds = Counter(r["kind"] for r in rows)
    confs = Counter(json.loads(r["output"])["confidence"] for r in rows)
    lengths = sorted(len(r["instruction"]) + len(r["output"]) for r in rows)
    print(
        f"Всего примеров: {len(rows)} (фактов {len(FACTS)}, частичных тем {len(PARTIAL)}, "
        f"категорий не по теме {len(OFF_TOPIC)})"
    )
    for kind, n in sorted(kinds.items(), key=lambda kv: -kv[1]):
        print(f"  {kind:10} {n:4}  ({n / len(rows):.0%})")
    print(
        "confidence, уникальных значений:",
        len(confs),
        "| доля отказов (0.0):",
        f"{kinds['off_topic'] / len(rows):.0%}",
    )
    print(
        f"train: {len(train)}  val: {len(val)}  test: {len(test)} (в обучение не входят)"
    )
    print(
        f"длина вопрос+ответ, симв.: медиана {lengths[len(lengths) // 2]}, max {lengths[-1]} "
        f"(~{lengths[-1] // 3} токенов: MAX_SEQ=512 хватает с запасом)"
    )
    print(f"файлы -> {OUT_DIR}")


if __name__ == "__main__":
    main()
