"""Промпты RAG-сервиса: наивный (уязвимый) и укреплённый.

Ключевая мысль урока по безопасности: текст документа для модели ничем не
отличается от текста инструкции. Разделение «данные / код» модель делает
только потому, что мы её об этом попросили — и просить надо явно, жёстко
и с разделителями, которые документ не может подделать.
"""

from __future__ import annotations

import secrets
from typing import Sequence

from .store import Hit

