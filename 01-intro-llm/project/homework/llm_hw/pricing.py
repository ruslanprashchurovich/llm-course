"""Цены облачных моделей — ЗАДАНИЕ 1 (числа взяты из урока 1.3 без изменений).

Локальная модель бесплатна, но полезно видеть, во что тот же запрос обошёлся бы
в облаке. Это ровно та арифметика, что мы считали «на бумаге» в уроке 1.3, —
теперь она считается на живых счётчиках токенов после каждого запроса.
"""

from __future__ import annotations

# Ориентировочные цены (USD за 1 млн токенов), август 2026 — как в уроке 1.3.
# Перед реальным расчётом сверьтесь с актуальным прайсом провайдера!
PRICES_USD_PER_1M: dict[str, tuple[float, float]] = {
    #  модель           (input, output)
    "gpt-4o-mini":     (0.15,  0.60),   # мини-класс OpenAI
    "gpt-4o":          (2.50, 10.00),   # флагман OpenAI
    "claude-haiku":    (0.80,  4.00),   # быстрый класс Anthropic
    "claude-sonnet":   (3.00, 15.00),   # старший класс Anthropic
    "deepseek-chat":   (0.27,  1.10),   # DeepSeek
}

USD_RUB = 90  # условный курс для прикидок — подставьте актуальный (урок 1.3)


def request_cost_usd(model: str, input_tokens: int, output_tokens: int) -> float:
    """Стоимость одного запроса к облачной модели, в долларах (урок 1.3)."""
    price_in, price_out = PRICES_USD_PER_1M[model]
    return (
        input_tokens / 1_000_000 * price_in
        + output_tokens / 1_000_000 * price_out
    )
